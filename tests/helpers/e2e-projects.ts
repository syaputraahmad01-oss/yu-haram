const MARKET_BOUNDARY = `import { Component, type ErrorInfo, type ReactNode } from 'react'

interface BoundaryState { hasError: boolean; message: string }

export class ErrorBoundary extends Component<{ children: ReactNode }, BoundaryState> {
  state: BoundaryState = { hasError: false, message: '' }

  static getDerivedStateFromError(error: Error): BoundaryState {
    return { hasError: true, message: error.message }
  }

  componentDidCatch(error: Error, info: ErrorInfo): void {
    console.error('Marketplace error boundary:', error, info.componentStack)
  }

  render(): ReactNode {
    if (this.state.hasError) {
      return (
        <div role="alert" className="error-state">
          <h2>Terjadi kesalahan</h2>
          <p>{this.state.message}</p>
          <button onClick={() => this.setState({ hasError: false, message: '' })}>Coba lagi</button>
        </div>
      )
    }
    return this.props.children
  }
}`

