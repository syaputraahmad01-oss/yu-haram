const INVENTORY_TYPES = `export type ItemStatus = 'tersedia' | 'habis' | 'dipesan'

export interface InventoryItem {
  id: string
  name: string
  sku: string
  stock: number
  minStock: number
  status: ItemStatus
}

export function deriveStatus(stock: number, minStock: number): ItemStatus {
  if (stock <= 0) return 'habis'
  if (stock <= minStock) return 'dipesan'
  return 'tersedia'
}`

const INVENTORY_STORAGE = `import { deriveStatus, type InventoryItem } from './types'

const KEY = 'inventory-items-v1'

export function loadItems(): InventoryItem[] {
  try {
    const raw = localStorage.getItem(KEY)
    if (!raw) return []
    const parsed = JSON.parse(raw) as InventoryItem[]
    // Data consistency: recompute status from stock on every load.
    return parsed.map(item => ({ ...item, status: deriveStatus(item.stock, item.minStock) }))
  } catch {
    return []
  }
}

export function saveItems(items: InventoryItem[]): void {
  localStorage.setItem(KEY, JSON.stringify(items))
}

export function validateItem(input: { name: string; sku: string; stock: number; minStock: number }): string | null {
  if (input.name.trim().length < 3) return 'Nama barang minimal 3 karakter.'
  if (!/^[A-Z]{2}-\\d{3,}$/.test(input.sku)) return 'SKU harus berformat AB-123.'
  if (input.stock < 0 || input.minStock < 0) return 'Stok tidak boleh negatif.'
  return null
}`

const INVENTORY_APP = `import { useEffect, useState } from 'react'
import { ItemForm } from './components/ItemForm'
import { ItemTable } from './components/ItemTable'
import { loadItems, saveItems } from './storage'
import type { InventoryItem } from './types'

export default function App() {
  const [items, setItems] = useState<InventoryItem[]>([])
  const [formOpen, setFormOpen] = useState(false)

  useEffect(() => { setItems(loadItems()) }, [])

  const persist = (next: InventoryItem[]) => {
    setItems(next)
    saveItems(next)
  }

  return (
    <div className="container">
      <h1>Inventory Management Gudang</h1>
      <button onClick={() => setFormOpen(true)}>Tambah barang</button>
      {formOpen
        ? <ItemForm onCancel={() => setFormOpen(false)} onSave={item => { persist([item, ...items]); setFormOpen(false) }} />
        : null}
      <ItemTable
        items={items}
        onDelete={id => persist(items.filter(item => item.id !== id))}
        onRestock={(id, qty) => persist(items.map(item => item.id === id ? { ...item, stock: item.stock + qty } : item))}
      />
    </div>
  )
}`

